"""Find the repository's files and decide which ones are worth parsing.

Classification follows the spirit of GitHub linguist: vendored and generated code, data and binaries
stay on the map as collapsed assets but are never parsed for symbols.
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

import pathspec

from .languages import LangInfo, detect

MAX_PARSE_BYTES = 1_000_000

VENDOR_DIRS = {"node_modules", "bower_components", "jspm_packages", "vendor", "vendors", "third_party",
               "thirdparty", "3rdparty", ".venv", "venv", "site-packages", "__pypackages__", "Pods",
               "Carthage", ".yarn", ".pnpm-store", ".bundle"}
GENERATED_DIRS = {"dist", "build", "out", ".next", ".nuxt", ".svelte-kit", ".output", "coverage",
                  "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".tox", ".gradle", "target",
                  ".turbo", ".parcel-cache", ".angular", ".expo", ".docusaurus", "storybook-static"}
GENERATED_NAMES = re.compile(
    r"(\.min\.(js|css)$|\.map$|\.bundle\.js$|\.pb\.go$|_pb2(_grpc)?\.pyi?$|\.g\.dart$|\.generated\.\w+$|"
    r"^(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|poetry\.lock|uv\.lock|Pipfile\.lock|Cargo\.lock|"
    r"go\.sum|composer\.lock|Gemfile\.lock|bun\.lockb)$)", re.I)
GENERATED_MARK = re.compile(rb"@generated|DO NOT EDIT|auto-generated|autogenerated by", re.I)
BINARY_EXT = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".ico", ".icns", ".tif", ".tiff", ".psd",
              ".pdf", ".zip", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".tar", ".jar", ".war", ".whl",
              ".mp4", ".mov", ".avi", ".webm", ".mp3", ".wav", ".flac", ".ogg", ".woff", ".woff2", ".ttf",
              ".otf", ".eot", ".so", ".dll", ".dylib", ".exe", ".bin", ".o", ".a", ".lib", ".pyc", ".class",
              ".pt", ".pth", ".ckpt", ".safetensors", ".onnx", ".npy", ".npz", ".pkl", ".pickle", ".h5",
              ".hdf5", ".parquet", ".arrow", ".feather", ".glb", ".gltf", ".fbx", ".obj", ".ply", ".stl",
              ".blend", ".exr", ".hdr", ".db", ".sqlite", ".sqlite3", ".xlsx", ".xls", ".docx", ".pptx"}
DATA_EXT = {".csv", ".tsv", ".jsonl", ".ndjson", ".log"}
TEST_DIRS = {"test", "tests", "__tests__", "spec", "specs", "testing", "e2e"}
TEST_NAME = re.compile(r"(^test_.*\.py$|_test\.(py|go|rs|dart|exs?)$|\.(test|spec)\.[cm]?[jt]sx?$|Tests?\.(java|kt|cs|swift)$|_spec\.rb$)")
DOC_EXT = {".md", ".mdx", ".markdown", ".rst", ".adoc", ".txt"}
CONFIG_EXT = {".yaml", ".yml", ".toml", ".ini", ".cfg", ".conf", ".json", ".jsonc", ".env", ".example",
              ".properties", ".gitignore", ".dockerignore", ".editorconfig"}
CONFIG_NAMES = {"dockerfile", "makefile", "containerfile", "procfile", "justfile", ".env"}


@dataclass
class FileEntry:
    path: str          # POSIX path relative to the repo root
    size: int
    kind: str          # source | test | config | docs | generated | vendored | data | binary | other
    lang: str | None
    tier: str          # "1" | "2" | "outline" | "none"
    mtime: int = 0     # st_mtime_ns, to skip unchanged files on the next scan

    @property
    def parse(self) -> bool:
        return self.kind in ("source", "test", "config", "docs") and self.tier != "none"


def list_files(root: Path) -> list[str]:
    """git-tracked plus untracked-but-not-ignored files; plain walk outside git."""
    try:
        out = subprocess.run(
            ["git", "-c", "core.quotepath=off", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            cwd=root, capture_output=True, check=True,
        ).stdout
        paths = sorted({p for p in out.decode("utf-8", "surrogateescape").split("\0") if p})
    except (subprocess.CalledProcessError, FileNotFoundError):
        paths = _walk(root)
    ignore = _ignore_spec(root)
    return [p for p in paths if not p.startswith(".codemap/") and not (ignore and ignore.match_file(p))]


def _walk(root: Path) -> list[str]:
    spec = None
    gi = root / ".gitignore"
    if gi.exists():
        spec = pathspec.PathSpec.from_lines("gitignore", gi.read_text("utf-8", "replace").splitlines())
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for f in filenames:
            rel = Path(dirpath, f).relative_to(root).as_posix()
            if not (spec and spec.match_file(rel)):
                out.append(rel)
    return sorted(out)


def _ignore_spec(root: Path):
    f = root / ".codemapignore"
    if not f.exists():
        return None
    return pathspec.PathSpec.from_lines("gitignore", f.read_text("utf-8", "replace").splitlines())


def classify(root: Path, path: str, known: dict | None = None) -> FileEntry:
    full = root / path
    try:
        st = full.stat()
        size, mtime = st.st_size, st.st_mtime_ns
    except OSError:
        size, mtime = 0, 0
    p = PurePosixPath(path)
    parts = p.parts[:-1]
    name, ext = p.name, p.suffix.lower()
    info: LangInfo = detect(path)

    def entry(kind):
        return FileEntry(path, size, kind, info.lang, info.tier, mtime)

    prev = (known or {}).get(path)
    if prev and prev[0] == size and prev[1] == mtime:  # unchanged since the last scan: no need to read it
        return entry(prev[2])
    if any(d in VENDOR_DIRS for d in parts):
        return entry("vendored")
    if any(d in GENERATED_DIRS for d in parts) or GENERATED_NAMES.search(name):
        return entry("generated")
    if ext in BINARY_EXT:
        return entry("binary")
    if ext in DATA_EXT:
        return entry("data")
    head = b""
    try:
        with open(full, "rb") as fh:
            head = fh.read(4096)
    except OSError:
        pass
    if b"\0" in head:
        return entry("binary")
    if size > MAX_PARSE_BYTES or (ext in (".json", ".jsonc") and size > 256_000):
        return entry("data")
    if GENERATED_MARK.search(head[:600]):
        return entry("generated")
    if TEST_NAME.search(name) or any(d.lower() in TEST_DIRS for d in parts):
        if info.tier in ("1", "2"):
            return entry("test")
    if ext in DOC_EXT:
        return entry("docs")
    if ext in CONFIG_EXT or name.lower() in CONFIG_NAMES or name.lower().startswith("dockerfile"):
        return entry("config")
    if info.tier in ("1", "2"):
        return entry("source")
    if info.tier == "outline":
        return entry("config")
    return entry("other")


def discover(root: Path, known: dict | None = None) -> list[FileEntry]:
    """`known`: path → (size, mtime_ns, kind) from the previous scan, to skip re-classifying unchanged files."""
    return [classify(root, p, known) for p in list_files(root)]
