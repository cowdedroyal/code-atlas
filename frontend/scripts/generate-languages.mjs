import { createRequire } from "node:module";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const core = require("highlight.js/lib/core");
const directory = dirname(require.resolve("highlight.js/lib/languages/python"));
const names = readdirSync(directory).filter(n => n.endsWith(".js") && !n.endsWith(".js.js")).map(n => n.slice(0, -3)).sort();
for (const name of names) core.registerLanguage(name, require(`highlight.js/lib/languages/${name}`));
const aliases = { tsx: "typescript", jsx: "javascript", ecmascript: "javascript", c_sharp: "csharp", shell: "bash",
  toml: "ini", commonlisp: "lisp", elisp: "lisp", ocaml_interface: "ocaml", fsharp_signature: "fsharp",
  cuda: "cpp", hcl: "terraform", tf: "terraform", objc: "objectivec", objcpp: "objectivec", make: "makefile",
  vue: "vue", svelte: "svelte" };
for (const name of names) for (const alias of core.getLanguage(name).aliases ?? []) if (!(alias in aliases)) aliases[alias] = name;
const dependencies = {};
for (const name of names) {
  const source = readFileSync(resolve(directory, name + ".js"), "utf8");
  const deps = new Set();
  for (const m of source.matchAll(/(?:subLanguage\s*:|getLanguage\()\s*(?:\[([^\]]*)\]|['"]([^'"]+)['"])/g)) {
    for (const dep of m[2] ? [m[2]] : [...m[1].matchAll(/['"]([^'"]+)['"]/g)].map(x => x[1])) {
      const target = aliases[dep] ?? dep;
      if (names.includes(target) && target !== name) deps.add(target);
    }
  }
  const required = source.match(/Requires:\s*([^\n]+)/)?.[1] ?? "";
  for (const m of required.matchAll(/([\w-]+)\.js/g)) if (names.includes(m[1])) deps.add(m[1]);
  if (deps.size) dependencies[name] = [...deps];
}
const root = resolve(import.meta.dirname, "..");
writeFileSync(resolve(root, "src/languageNames.ts"), `// Generated by scripts/generate-languages.mjs; all grammars remain lazy.\nexport const grammarNames: string[] = ${JSON.stringify([...names, "vue", "svelte"])};\nexport const languageAliases: Record<string, string> = ${JSON.stringify(aliases)};\n`);
writeFileSync(resolve(root, "src/languageGrammars.ts"), `// Generated by scripts/generate-languages.mjs.\nimport type { LanguageFn } from "highlight.js";\nexport const grammars: Record<string, () => Promise<{ default: LanguageFn }>> = {\n${names.map(n => `  ${JSON.stringify(n)}: () => import("highlight.js/lib/languages/${n}"),`).join("\n")}\n};\nexport const dependencies: Record<string, string[]> = ${JSON.stringify(dependencies)};\n`);
writeFileSync(resolve(root, "../src/code_atlas/highlight_languages.json"), JSON.stringify({ names: [...names, "vue", "svelte"], aliases }, null, 2) + "\n");
console.log(`Registered ${names.length} lazy language grammars plus Vue/Svelte.`);
